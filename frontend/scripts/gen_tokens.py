"""Generate src/styles/tokens.css (Specimen v2: Ink & Pigment). Run: python scripts/gen_tokens.py"""
import math, pathlib

def h2rgb(h): h = h.lstrip("#"); return [int(h[i:i+2], 16) / 255 for i in (0, 2, 4)]
def lin(c): return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
def delin(c): return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
def to_oklch(h):
    r, g, b = map(lin, h2rgb(h))
    l = (0.4122214708*r + 0.5363325363*g + 0.0514459929*b) ** (1/3)
    m = (0.2119034982*r + 0.6806995451*g + 0.1073969566*b) ** (1/3)
    s = (0.0883024619*r + 0.2817188376*g + 0.6299787005*b) ** (1/3)
    L = 0.2104542553*l + 0.7936177850*m - 0.0040720468*s
    a = 1.9779984951*l - 2.4285922050*m + 0.4505937099*s
    bb = 0.0259040371*l + 0.7827717662*m - 0.8086757660*s
    return L, math.hypot(a, bb), math.degrees(math.atan2(bb, a)) % 360
def from_oklch(L, C, H):
    a, b = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l = (L + 0.3963377774*a + 0.2158037573*b) ** 3
    m = (L - 0.1055613458*a - 0.0638541728*b) ** 3
    s = (L - 0.0894841775*a - 1.2914855480*b) ** 3
    rgb = [4.0767416621*l - 3.3077115913*m + 0.2309699292*s, -1.2684380046*l + 2.6097574011*m - 0.3413193965*s, -0.0041960863*l - 0.7034186147*m + 1.7076147010*s]
    return [delin(x) if x > 0 else 0 for x in rgb]
def in_gamut(rgb): return all(-1e-4 <= x <= 1 + 1e-4 for x in rgb)
def hexof(rgb): return "#" + "".join(f"{round(min(max(x,0),1)*255):02x}" for x in rgb)
def lum(h): return sum(w * lin(c) for w, c in zip((0.2126, 0.7152, 0.0722), h2rgb(h)))
def cr(a, b): x, y = sorted((lum(a), lum(b)), reverse=True); return (x + 0.05) / (y + 0.05)
def mix(a, b, p):  # srgb color-mix(a p%, b)
    return hexof([x * p + y * (1 - p) for x, y in zip(h2rgb(a), h2rgb(b))])
def text_variant(h, bgs, dark):
    """Same hue, lightness shifted until >= 4.6:1 on every background (chroma reduced if out of gamut)."""
    if min(cr(h, b) for b in bgs) >= 4.6: return h
    L, C, H = to_oklch(h)
    for step in range(1, 80):
        L2 = L + (0.01 * step if dark else -0.01 * step)
        c = C
        while c > 0:
            rgb = from_oklch(L2, c, H)
            if in_gamut(rgb): break
            c -= 0.005
        cand = hexof(from_oklch(L2, max(c, 0), H))
        if min(cr(cand, b) for b in bgs) >= 4.6: return cand
    raise SystemExit(f"no text variant for {h}")
def ok(h):
    L, C, H = to_oklch(h); return f"oklch({L*100:.1f}% {C:.3f} {H:.1f})"

THEMES = {
  "light": dict(selector=':root,\n:root[data-theme="light"]', scheme="light", base=dict(
      bg="#F2EDE3", surface="#FBF8F2", raised="#FFFFFF", ink="#121418", **{"ink-2": "#575C66"}, rule="#D9D1C1"),
    pig=dict(indigo="#1E2A78", peacock="#00727A", marigold="#F2A007", riso="#E8447C", vermilion="#D23B1F", leaf="#2E7D32", terracotta="#B4532A",
             c0="#7A7F88", c1="#3A6EA5", c2="#1E2A78", c3="#00727A", c4="#C4780A")),
  "dark": dict(selector=':root[data-theme="dark"]', scheme="dark", base=dict(
      bg="#0D0F14", surface="#151922", raised="#1C2130", ink="#ECE7DD", **{"ink-2": "#9BA3AE"}, rule="#262C38"),
    pig=dict(indigo="#8C9BFF", peacock="#3CC6C0", marigold="#FFBE3D", riso="#FF6FA0", vermilion="#FF6B57", leaf="#6CCB7A", terracotta="#E0835A",
             c0="#9AA0A8", c1="#0B94E7", c2="#8265A3", c3="#2C8766", c4="#B16A08")),
}
SPECIES = dict(bov="indigo", cap="leaf", avi="marigold", can="terracotta", fel="peacock")

out = ["/* Specimen v2 — Ink & Pigment. GENERATED by scripts/gen_tokens.py; edit there, not here.",
       "   Hex values first (fallback), then an @supports layer in oklch with the same colours.",
       "   Pigments are for fills, marks and borders; *-text variants are the same hue shifted in",
       "   oklch lightness until they pass WCAG AA (4.5:1) as text on every background of the theme.",
       "   Checked by scripts/check-contrast.mjs. */", ""]
for name, t in THEMES.items():
    b, p = t["base"], t["pig"]
    dark = name == "dark"
    sunk = mix(b["ink"], b["bg"], 0.04)
    bgs = [b["bg"], b["surface"], b["raised"], sunk]
    vals = {**b}
    vals.update(p)
    for k, h in p.items(): vals[f"{k}-text"] = text_variant(h, bgs, dark)
    lines = [f"{t['selector']} {{", f"  color-scheme: {t['scheme']};", ""]
    lines += [f"  --{k}: {v.lower()};" for k, v in vals.items()]
    lines += ["",
      "  /* Derived tints (color-mix only; no ad-hoc colours) */",
      "  --surface-sunk: color-mix(in srgb, var(--ink) 4%, var(--bg));",
      "  --rule-strong: color-mix(in srgb, var(--ink) 14%, var(--rule));",
      "  --on-accent: var(--surface);",
      "  --focus: var(--riso-text);",
      f"  --on-marigold: var(--{'bg' if dark else 'ink'});",
      f"  --meter-face: var(--{'bg' if dark else 'ink'});",
      "  --meter-off: color-mix(in srgb, var(--ink-2) 30%, var(--meter-face));",
      "  --scrim: color-mix(in srgb, var(--ink) 22%, transparent);",
      "  --selection: color-mix(in srgb, var(--marigold) 35%, transparent);",
      "  --grid-minor: color-mix(in srgb, var(--rule) 55%, transparent);",
      "  --grid-major: var(--rule);",
      "  --halftone-ink: color-mix(in srgb, var(--ink) 22%, transparent);",
      f"  --grain-opacity: {0.035 if dark else 0.04};",
      "  /* Species stripes map onto the pigments */"]
    lines += [f"  --sp-{k}: var(--{v});" for k, v in SPECIES.items()]
    lines += ["}", "", "@supports (color: oklch(0% 0 0)) {", f"  {t['selector'].replace(chr(10), ' ')} {{"]
    lines += [f"    --{k}: {ok(v)};" for k, v in vals.items() if k not in ("raised",) or True]
    lines += ["  }", "}", ""]
    out += lines
    globals()[f"VALS_{name}"] = vals; globals()[f"SUNK_{name}"] = sunk

out.append(pathlib.Path("scripts/tokens.static.css").read_text(encoding="utf-8"))
pathlib.Path("src/styles/tokens.css").write_text("\n".join(out), encoding="utf-8", newline="\n")
for name in THEMES:
    v = globals()[f"VALS_{name}"]
    print(name, "sunk", globals()[f"SUNK_{name}"], {k: v[k] for k in v if k.endswith("-text") and v[k] != v[k[:-5]]})
